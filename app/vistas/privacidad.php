<h1>Política de privacidad de TuRenta</h1>
<p><small>Última actualización: 28 de octubre de 2026</small></p>

<p>TuRenta es un sistema de fechas, cotizaciones, contratos, cobros e invitados para salones de eventos, quintas y haciendas, hecho por <b>Tukán Software</b> (QF Producciones, Ecuador). Esta política explica qué datos guarda TuRenta, para qué y cómo puedes pedir que se borren. Se aplica a la página <b>turenta.tukanec.com</b> y a la app <b>TuRenta</b> para Android (Google Play), que abre esa misma página.</p>

<h2>Quién es el responsable</h2>
<ul>
<li><b>Cada local</b> (salón, quinta o hacienda) es el responsable de los datos de sus clientes, invitados y personal. TuRenta los guarda por cuenta del local.</li>
<li><b>Tukán Software</b> es responsable de los datos de la cuenta del local (dueño, plan y pagos del plan).</li>
<li>Contacto: <a href="mailto:info@tukansoftware.com">info@tukansoftware.com</a> · WhatsApp 098 366 2181.</li>
</ul>

<h2>Qué datos guardamos</h2>
<ul>
<li><b>Del dueño y su equipo:</b> nombre, correo, teléfono y contraseña (cifrada).</li>
<li><b>De los clientes del local:</b> nombre, cédula o RUC, teléfono, correo, dirección, los datos del evento, cotizaciones, contratos, pagos y la imagen de la firma del contrato con la fecha, la dirección IP y el navegador desde donde se firmó (para poder comprobar la firma).</li>
<li><b>De los invitados:</b> nombre, teléfono si lo da quien organiza, mesa, restricciones de comida y si confirmaron o ingresaron al evento.</li>
<li><b>Del personal de eventos:</b> nombre, cédula, teléfono, eventos asignados y pagos.</li>
<li><b>Pagos:</b> montos y forma de pago. Los pagos con tarjeta los procesa <b>Payphone</b>: TuRenta <b>no</b> guarda números de tarjeta. Si se sube un comprobante de transferencia, se guarda la imagen.</li>
<li><b>Avisos:</b> si alguien conecta Telegram, se guarda su número de chat para enviarle avisos.</li>
<li><b>Ayuda e inteligencia artificial:</b> las preguntas que se escriben en Ayuda y, si el local usa el Asistente IA, el mensaje que pega para armar una cotización.</li>
<li><b>Datos técnicos:</b> una cookie de sesión, una cookie que indica si se entra desde la app y registros básicos del servidor (fecha, dirección IP) para seguridad.</li>
<li>La app <b>no</b> pide la ubicación, los contactos, el micrófono ni otros permisos del celular, y no usa el identificador de publicidad.</li>
</ul>

<h2>Para qué los usamos</h2>
<ul>
<li>Para que el local pueda organizar sus fechas, cotizar, firmar contratos, cobrar, coordinar el día del evento y controlar el ingreso de invitados.</li>
<li>Para cobrar y renovar el plan de TuRenta.</li>
<li>No vendemos datos, no mostramos publicidad y no usamos los datos para otra cosa.</li>
</ul>

<h2>Con quién se comparten</h2>
<ul>
<li>Solo con los servicios necesarios para que funcione: el servidor y la red de Cloudflare, Payphone (pagos con tarjeta), Telegram (avisos, solo si se activa) y Anthropic (el servicio de inteligencia artificial que responde la Ayuda y arma borradores de cotización; no usa esos datos para entrenar ni para otra cosa).</li>
<li>Con autoridades, solo si la ley lo exige.</li>
</ul>

<h2>Cuánto tiempo se guardan</h2>
<p>Mientras la cuenta del local esté activa. Si el local deja TuRenta, sus datos se borran a los 90 días, salvo lo que la ley obligue a guardar (por ejemplo, contratos y registros de pagos).</p>

<h2 id="borrar-cuenta">Tus derechos y cómo borrar tu cuenta o tus datos</h2>
<p>Según la Ley Orgánica de Protección de Datos Personales del Ecuador, puedes pedir ver, corregir o borrar tus datos.</p>
<ul>
<li><b>Dueño de un local:</b> escribe desde el correo de la cuenta a <a href="mailto:info@tukansoftware.com?subject=Borrar%20mi%20cuenta%20de%20TuRenta">info@tukansoftware.com</a> con el asunto "Borrar mi cuenta de TuRenta". Lo hacemos en un máximo de 15 días. También puedes pedirlo desde el sistema o la app: <b>Más → Mi cuenta → Borrar mi cuenta</b>. Se borran la cuenta, los usuarios y todos los datos del local, salvo lo que la ley obligue a guardar.</li>
<li><b>Cliente o invitado de un local:</b> pide al local que borre tus datos, o escríbenos al mismo correo indicando el local y tu teléfono.</li>
<li><b>Personal o miembro del equipo:</b> pide al dueño que te desactive, o escríbenos.</li>
</ul>

<h2>Seguridad</h2>
<p>La conexión va cifrada (HTTPS), las contraseñas se guardan cifradas, los enlaces que se mandan a clientes e invitados son secretos y cada local solo ve sus propios datos.</p>

<h2>Cambios</h2>
<p>Si cambiamos esta política, publicaremos la nueva versión aquí con su fecha.</p>
